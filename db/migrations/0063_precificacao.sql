  produto_id uuid primary key references app.produtos(id) on delete cascade,
  custo_brl numeric(14,4) not null check (custo_brl >= 0),
  frete_brl numeric(14,4) check (frete_brl >= 0),
  origem text not null check (length(origem) <= 200),
  confirmado boolean not null default false,
  carregado_em timestamptz not null default now()
);
comment on table app.custo_planilha is 'Custo por unidade lido da planilha PRODUCTOS VC, com a aba e a linha de onde veio. confirmado = casamento seguro (já aplicado ao produto).';

