insert into app.custo_planilha (produto_id, custo_brl, frete_brl, origem, confirmado)
select p.id, c.custo, c.frete, c.origem, c.confirmado from _cp c join app.produtos p on p.codigo = c.codigo
on conflict (produto_id) do update set custo_brl = excluded.custo_brl, frete_brl = excluded.frete_brl,
  origem = excluded.origem, confirmado = excluded.confirmado, carregado_em = now();

