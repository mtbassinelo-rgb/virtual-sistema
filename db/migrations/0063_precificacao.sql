update app.produtos p set custo_unitario_brl = cp.custo_brl, custo_origem = left('Planilha PRODUCTOS VC › ' || cp.origem, 120), custo_atualizado_em = now()
  from app.custo_planilha cp where cp.produto_id = p.id and cp.confirmado and p.custo_unitario_brl is null;
update app.produtos p set frete_unidade_brl = cp.frete_brl
  from app.custo_planilha cp where cp.produto_id = p.id and cp.confirmado and cp.frete_brl is not null and p.frete_unidade_brl is null;

