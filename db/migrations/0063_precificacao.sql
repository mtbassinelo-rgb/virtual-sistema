--    nunca mexe em preço de venda nem ativa/desativa produto.
--    Casamentos incertos ficam só como "parecido" para o gestor conferir na tela.
-- 2) app.precificacao_py(): uma linha por produto ativo com custo, preços, margens e preço sugerido.
-- =====================================================================

