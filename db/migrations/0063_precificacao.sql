-- ---------------------------------------------------------------------
-- Tela de precificação: tudo de um produto numa linha
-- situacao: sem_custo · sem_preco · abaixo_minimo · margem_baixa · margem_alta · ok
-- ---------------------------------------------------------------------
create or replace function app.precificacao_py()
returns table (produto_id uuid, codigo text, nome text, marca text, foto text, tipo text, caixa int,
               custo_brl numeric, custo_origem text, frete_brl numeric, planilha_custo numeric, planilha_origem text,
               custo_real_gs numeric, entrega_unidade_gs numeric, preco_minimo numeric,
               preco_normal numeric, preco_vip numeric, contribuicao_normal numeric, contribuicao_vip numeric,
               alvo_normal numeric, alvo_vip numeric, sugerido_normal numeric, sugerido_vip numeric,
               vendido_90 numeric, saldo numeric, motor boolean, papel text, situacao text)
language plpgsql stable security definer set search_path = app, pg_temp as $$
#variable_conflict use_column
declare v_an numeric := coalesce(app.param('margem_alvo_normal'), 35);
        v_av numeric := coalesce(app.param('margem_alvo_vip'), 25);
        v_tol numeric := coalesce(app.param('sugestao_tolerancia_pct'), 3) / 100;
        v_arred numeric := greatest(coalesce(app.param('arredondamento_gs'), 500), 1);
begin
  if not coalesce(app.e_gestao(), false) then raise exception 'Só gestão vê a precificação.'; end if;
  return query
  with r as (
    select r.*, p.foto as ft, p.custo_origem as orig, cp.custo_brl as pc, cp.origem as po, cp.confirmado as pconf,
           mi.gatilho, mi.papel as pap,
           coalesce(mi.margem_alvo_normal, v_an) as an, coalesce(mi.margem_alvo_vip, v_av) as av
      from app.rentabilidade_py() r
      join app.produtos p on p.id = r.produto_id
      left join app.custo_planilha cp on cp.produto_id = r.produto_id
      left join app.marcas_inteligencia mi on mi.marca = coalesce(nullif(trim(r.marca), ''), 'Sem marca')
  ), s as (
    select r.*,
      case when r.custo_real_gs is not null and r.entrega_unidade_gs is not null and 1 - r.impostos_pct / 100 - r.an / 100 > 0 then
        greatest(coalesce(r.preco_minimo, 0), ceil(((r.custo_real_gs + r.entrega_unidade_gs) / (1 - r.impostos_pct / 100 - r.an / 100)) / v_arred) * v_arred) end as sn,
      case when r.custo_real_gs is not null and r.entrega_unidade_gs is not null and 1 - r.impostos_pct / 100 - r.av / 100 > 0 then
        greatest(coalesce(r.preco_minimo, 0), ceil(((r.custo_real_gs + r.entrega_unidade_gs) / (1 - r.impostos_pct / 100 - r.av / 100)) / v_arred) * v_arred) end as sv
      from r
  )
  select s.produto_id, s.codigo, s.nome, s.marca, s.ft, s.tipo, s.unidades_caixa,
         s.custo_brl, s.orig, s.frete_brl,
         case when s.pc is not null and (s.custo_brl is null or abs(s.pc - s.custo_brl) > 0.005) then s.pc end,
         case when s.pc is not null and (s.custo_brl is null or abs(s.pc - s.custo_brl) > 0.005) then s.po end,
         s.custo_real_gs, s.entrega_unidade_gs, s.preco_minimo,
         s.preco_normal, s.preco_vip, s.contribuicao_normal, s.contribuicao_vip,
         s.an / 100, s.av / 100, s.sn, s.sv,
         s.vendido_90, s.saldo, coalesce(s.gatilho, false), coalesce(s.pap, 'acompanhar'),
         case
           when s.custo_brl is null then 'sem_custo'
           when s.preco_normal is null or s.preco_vip is null then 'sem_preco'
           when s.preco_minimo is not null and (s.preco_vip < s.preco_minimo or s.preco_normal < s.preco_minimo) then 'abaixo_minimo'
           when s.sv is not null and (s.preco_vip < s.sv * (1 - v_tol) or s.preco_normal < s.sn * (1 - v_tol)) then 'margem_baixa'
           when s.sv is not null and (s.preco_vip > s.sv * (1 + v_tol) and s.preco_normal > s.sn * (1 + v_tol)) then 'margem_alta'
           else 'ok'
         end
    from s;
end $$;

revoke execute on function app.precificacao_py() from public;
grant execute on function app.precificacao_py() to vc_app;
